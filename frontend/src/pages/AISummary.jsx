import { useLocation, useNavigate } from "react-router-dom";

function AISummary() {
  const navigate = useNavigate();
  const location = useLocation();

  const meeting = location.state?.meeting || null;

  // ================= DATE =================

  const formatDate = (date) => {
    if (!date) return "—";

    try {
      return new Date(date).toLocaleDateString("en-GB", {
        day: "numeric",
        month: "long",
        year: "numeric",
      });
    } catch {
      return "—";
    }
  };

  // ================= DURATION =================

  const formatDuration = (minutes) => {
    if (!minutes || Number(minutes) <= 0) {
      return "0 Minutes";
    }

    return `${minutes} Minute${
      Number(minutes) === 1 ? "" : "s"
    }`;
  };

  // ================= PARTICIPANTS =================

  const participantCount =
    meeting?.participants?.length || 0;

  // ================= COPY SUMMARY =================

  const handleCopy = () => {
    if (!meeting?.aiSummary) {
      alert("No AI summary available to copy.");
      return;
    }

    navigator.clipboard
      .writeText(meeting.aiSummary)
      .then(() => {
        alert("AI Summary copied!");
      })
      .catch(() => {
        alert("Failed to copy summary.");
      });
  };

  // ================= DOWNLOAD SUMMARY =================

  const handleDownload = () => {
    if (!meeting?.aiSummary) {
      alert("No AI summary available to download.");
      return;
    }

    const summaryText = `
INTELLMEET
AI MEETING SUMMARY
========================================

MEETING INFORMATION
========================================

Meeting:
${meeting?.title || "Meeting"}

Date:
${formatDate(
      meeting?.endedAt ||
        meeting?.startedAt ||
        meeting?.createdAt
    )}

Duration:
${formatDuration(meeting?.duration)}

Participants:
${participantCount} ${
      participantCount === 1 ? "Member" : "Members"
    }

Status:
${meeting?.status || "—"}

Meeting Code:
${meeting?.meetingCode || "—"}

Created By:
${
  meeting?.createdBy?.name ||
  meeting?.createdBy?.email ||
  "Unknown"
}

Description:
${meeting?.description || "No description"}


========================================
AI GENERATED SUMMARY
========================================

${meeting.aiSummary}


========================================
PARTICIPANTS
========================================

${
  meeting?.participants?.length > 0
    ? meeting.participants
        .map(
          (participant, index) =>
            `${index + 1}. ${
              participant?.name ||
              participant?.email ||
              "Unknown User"
            }`
        )
        .join("\n")
    : "No participants recorded."
}


========================================
KEYWORDS
========================================

React
Node.js
MongoDB
WebRTC
Socket.io
AI Summary


========================================
Generated by IntelliMeet
========================================
`;

    const blob = new Blob([summaryText], {
      type: "text/plain;charset=utf-8",
    });

    const url = URL.createObjectURL(blob);

    const link = document.createElement("a");

    link.href = url;

    const fileName = `${meeting?.title || "Meeting"}-AI-Summary.txt`
      .replace(/[^a-z0-9-_ ]/gi, "")
      .replace(/\s+/g, "-");

    link.download = fileName;

    document.body.appendChild(link);

    link.click();

    document.body.removeChild(link);

    URL.revokeObjectURL(url);
  };

  // ================= UI =================

  return (
    <div className="min-h-screen bg-slate-950 text-white p-4 md:p-8">

      {/* ================= HEADER ================= */}

      <div className="flex justify-between items-start mb-8">

        {/* LEFT - TITLE */}

        <div className="flex items-center gap-3">

          <div className="text-4xl">
            🤖
          </div>

          <div>
            <h1 className="text-3xl md:text-4xl font-bold">
              AI Meeting Summary
            </h1>

            <p className="text-slate-400 mt-1">
              AI-powered analysis of your meeting
            </p>
          </div>

        </div>


        {/* RIGHT - BACK BUTTON */}

        <button
          onClick={() => navigate(-1)}
          className="bg-cyan-500 hover:bg-cyan-600 transition px-6 py-3 rounded-lg font-semibold"
        >
          ← Back
        </button>

      </div>


      {/* ================= MEETING INFORMATION ================= */}

      <div className="bg-slate-900 rounded-2xl p-6 mb-6 border border-slate-800 shadow-lg">

        <div className="flex items-center gap-3 mb-6">

          <div className="text-2xl">
            📋
          </div>

          <div>
            <h2 className="text-2xl font-bold">
              Meeting Information
            </h2>

            <p className="text-slate-400 text-sm">
              Basic information about this meeting
            </p>
          </div>

        </div>


        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">

          {/* Meeting */}

          <div className="bg-slate-800 p-5 rounded-xl border border-slate-700">

            <p className="text-slate-400 text-sm mb-2">
              Meeting
            </p>

            <h3 className="font-bold text-lg">
              {meeting?.title || "Meeting"}
            </h3>

          </div>


          {/* Duration */}

          <div className="bg-slate-800 p-5 rounded-xl border border-slate-700">

            <p className="text-slate-400 text-sm mb-2">
              Duration
            </p>

            <h3 className="font-bold text-lg">
              {formatDuration(meeting?.duration)}
            </h3>

          </div>


          {/* Participants */}

          <div className="bg-slate-800 p-5 rounded-xl border border-slate-700">

            <p className="text-slate-400 text-sm mb-2">
              Participants
            </p>

            <h3 className="font-bold text-lg">
              {participantCount}{" "}
              {participantCount === 1
                ? "Member"
                : "Members"}
            </h3>

          </div>


          {/* Date */}

          <div className="bg-slate-800 p-5 rounded-xl border border-slate-700">

            <p className="text-slate-400 text-sm mb-2">
              Date
            </p>

            <h3 className="font-bold text-lg">
              {formatDate(
                meeting?.endedAt ||
                  meeting?.startedAt ||
                  meeting?.createdAt
              )}
            </h3>

          </div>

        </div>

      </div>


      {/* ================= AI GENERATED SUMMARY ================= */}

      <div className="bg-slate-900 rounded-2xl p-6 mb-6 border border-slate-800 shadow-lg">

        <div className="flex flex-col md:flex-row justify-between items-start md:items-center gap-4 mb-6">

          <div className="flex items-center gap-3">

            <div className="text-2xl">
              🧠
            </div>

            <div>
              <h2 className="text-2xl font-bold">
                AI Generated Summary
              </h2>

              <p className="text-slate-400 text-sm">
                Generated using AI from meeting information
              </p>
            </div>

          </div>


          {meeting?.aiSummary && (
            <div className="bg-green-500/10 border border-green-500/30 text-green-400 px-4 py-2 rounded-lg text-sm font-medium">
              ✓ AI Generated
            </div>
          )}

        </div>


        {/* SUMMARY CONTENT */}

        <div className="bg-slate-800 rounded-xl p-6 border border-slate-700">

          {meeting?.aiSummary ? (

            <div className="text-slate-200 leading-8 whitespace-pre-wrap">
              {meeting.aiSummary}
            </div>

          ) : (

            <div className="text-center py-8">

              <div className="text-4xl mb-4">
                📝
              </div>

              <h3 className="text-xl font-bold mb-2">
                No AI Summary Available
              </h3>

              <p className="text-slate-400">
                Generate an AI summary from the
                Meeting Details page to view it here.
              </p>

            </div>

          )}

        </div>

      </div>


      {/* ================= MEETING OVERVIEW ================= */}

      <div className="bg-slate-900 rounded-2xl p-6 mb-6 border border-slate-800 shadow-lg">

        <div className="flex items-center gap-3 mb-6">

          <div className="text-2xl">
            📊
          </div>

          <div>
            <h2 className="text-2xl font-bold">
              Meeting Overview
            </h2>

            <p className="text-slate-400 text-sm">
              Information used by the AI assistant
            </p>
          </div>

        </div>


        <div className="grid md:grid-cols-2 gap-4">

          {/* Meeting Code */}

          <div className="bg-slate-800 rounded-xl p-5">

            <p className="text-slate-400 text-sm mb-2">
              Meeting Code
            </p>

            <p className="font-semibold">
              {meeting?.meetingCode || "—"}
            </p>

          </div>


          {/* Status */}

          <div className="bg-slate-800 rounded-xl p-5">

            <p className="text-slate-400 text-sm mb-2">
              Status
            </p>

            <p
              className={`font-semibold ${
                meeting?.status === "Completed"
                  ? "text-green-400"
                  : meeting?.status === "Live"
                    ? "text-red-400"
                    : "text-yellow-400"
              }`}
            >
              {meeting?.status || "—"}
            </p>

          </div>


          {/* Created By */}

          <div className="bg-slate-800 rounded-xl p-5">

            <p className="text-slate-400 text-sm mb-2">
              Created By
            </p>

            <p className="font-semibold">
              {meeting?.createdBy?.name ||
                meeting?.createdBy?.email ||
                "Unknown"}
            </p>

          </div>


          {/* Description */}

          <div className="bg-slate-800 rounded-xl p-5">

            <p className="text-slate-400 text-sm mb-2">
              Description
            </p>

            <p className="font-semibold">
              {meeting?.description ||
                "No description"}
            </p>

          </div>

        </div>

      </div>


      {/* ================= PARTICIPANTS ================= */}

      <div className="bg-slate-900 rounded-2xl p-6 mb-6 border border-slate-800 shadow-lg">

        <div className="flex items-center gap-3 mb-6">

          <div className="text-2xl">
            👥
          </div>

          <div>
            <h2 className="text-2xl font-bold">
              Participants
            </h2>

            <p className="text-slate-400 text-sm">
              Members associated with this meeting
            </p>
          </div>

        </div>


        {meeting?.participants?.length > 0 ? (

          <div className="grid sm:grid-cols-2 lg:grid-cols-3 gap-3">

            {meeting.participants.map(
              (participant, index) => (

                <div
                  key={
                    participant?._id || index
                  }
                  className="bg-slate-800 border border-slate-700 rounded-xl p-4 flex items-center gap-3"
                >

                  <div className="w-10 h-10 rounded-full bg-cyan-500/20 flex items-center justify-center">
                    👤
                  </div>

                  <div>

                    <p className="font-semibold">
                      {participant?.name ||
                        participant?.email ||
                        "Unknown User"}
                    </p>

                    {participant?.email && (
                      <p className="text-xs text-slate-400">
                        {participant.email}
                      </p>
                    )}

                  </div>

                </div>

              )
            )}

          </div>

        ) : (

          <p className="text-slate-500">
            No participants recorded.
          </p>

        )}

      </div>


      {/* ================= KEYWORDS ================= */}

      <div className="bg-slate-900 rounded-2xl p-6 mb-6 border border-slate-800 shadow-lg">

        <div className="flex items-center gap-3 mb-6">

          <div className="text-2xl">
            🔑
          </div>

          <div>
            <h2 className="text-2xl font-bold">
              Keywords
            </h2>

            <p className="text-slate-400 text-sm">
              Technologies and topics related to this meeting
            </p>
          </div>

        </div>


        <div className="flex flex-wrap gap-3">

          {[
            "React",
            "Node.js",
            "MongoDB",
            "WebRTC",
            "Socket.io",
            "AI Summary",
          ].map((keyword) => (

            <span
              key={keyword}
              className="bg-cyan-500/20 border border-cyan-400/30 text-cyan-300 px-4 py-2 rounded-full font-medium"
            >
              {keyword}
            </span>

          ))}

        </div>

      </div>


      {/* ================= ACTION BUTTONS ================= */}

      <div className="bg-slate-900 rounded-2xl p-6 border border-slate-800 shadow-lg">

        <div className="flex flex-wrap gap-4">

          {/* Download Summary */}

          <button
            onClick={handleDownload}
            disabled={!meeting?.aiSummary}
            className={`px-6 py-3 rounded-lg font-semibold transition ${
              meeting?.aiSummary
                ? "bg-green-500 hover:bg-green-600"
                : "bg-gray-600 opacity-60 cursor-not-allowed"
            }`}
          >
            📥 Download Summary
          </button>


          {/* Copy Summary */}

          <button
            onClick={handleCopy}
            disabled={!meeting?.aiSummary}
            className={`px-6 py-3 rounded-lg font-semibold transition ${
              meeting?.aiSummary
                ? "bg-cyan-500 hover:bg-cyan-600"
                : "bg-gray-600 opacity-60 cursor-not-allowed"
            }`}
          >
            📋 Copy Summary
          </button>

        </div>

      </div>

    </div>
  );
}

export default AISummary;